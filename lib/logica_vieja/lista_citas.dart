// Estructura de datos más profesional
class Cita {
  final String nombre;
  final String hora;
  final String fecha;
  final String codigo;

  Cita(
      {required this.nombre,
      required this.hora,
      required this.fecha,
      required this.codigo});

  // Método para convertir el objeto Cita a un Map<String, String>
  Map<String, String> toMap() {
    return {'nome': nombre, 'data': fecha, 'ora': hora};
  }
}